/* =========================================
   STORE KAKAO MAP 시작
========================================= */


/* =========================================
   지도 HTML 요소 가져오기
========================================= */

const mapContainer = document.getElementById("storeMap");


/* =========================================
   매장 좌표 설정

   현재는 강남역 인근 예시 좌표입니다.
   실제 매장 좌표로 변경 가능합니다.
========================================= */

const storeLat = 37.4979;
const storeLng = 127.0276;


/* =========================================
   지도 옵션 설정
========================================= */

const mapOption = {

  center: new kakao.maps.LatLng(
    storeLat,
    storeLng
  ),

  level: 5

};


/* =========================================
   카카오 지도 생성
========================================= */

const map = new kakao.maps.Map(
  mapContainer,
  mapOption
);


/* =========================================
   매장 위치 생성
========================================= */

const storePosition = new kakao.maps.LatLng(
  storeLat,
  storeLng
);


/* =========================================
   매장 마커 생성
========================================= */

const marker = new kakao.maps.Marker({

  position: storePosition

});


/* =========================================
   지도에 마커 표시
========================================= */

marker.setMap(map);


/* =========================================
   지도 확대 / 축소 컨트롤 생성
========================================= */

const zoomControl = new kakao.maps.ZoomControl();


/* =========================================
   확대 / 축소 컨트롤 추가
========================================= */

map.addControl(
  zoomControl,
  kakao.maps.ControlPosition.RIGHT
);


/* =========================================
   매장명 인포윈도우 생성
========================================= */

const infoWindow = new kakao.maps.InfoWindow({

  content:
    '<div style="' +
    'padding:8px 12px;' +
    'font-size:13px;' +
    'white-space:nowrap;' +
    '">' +
    '까페온 24 강남역점' +
    '</div>'

});


/* =========================================
   마커 클릭 이벤트
========================================= */

kakao.maps.event.addListener(
  marker,
  "click",
  function () {

    infoWindow.open(
      map,
      marker
    );

  }
);


/* =========================================
   STORE KAKAO MAP 끝
========================================= */