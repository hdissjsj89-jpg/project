$(function () {


  /* ===================================
     1. fadeOut
     빨간색 박스를 부드럽게 숨기기
  =================================== */

  $("#fadeOutBtn").click(function () {

    $(".red-box").fadeOut(1000);

  });



  /* ===================================
     2. fadeIn
     빨간색 박스를 부드럽게 보여주기
  =================================== */

  $("#fadeInBtn").click(function () {

    $(".red-box").fadeIn(1000);

  });



  /* ===================================
     3. fadeToggle
     초록색 박스

     첫 클릭  → 부드럽게 숨김
     다음 클릭 → 부드럽게 나타남
  =================================== */

  $("#fadeToggleBtn").click(function () {

    $(".green-box").fadeToggle(1000);

  });



  /* ===================================
     4. slideUp
     #ffcc00 박스의 높이를
     위쪽으로 접으면서 0으로 만들기
  =================================== */

  $("#slideUpBtn").click(function () {

    $(".yellow-box").slideUp(1000);

  });



  /* ===================================
     5. slideDown
     #ffcc00 박스를
     다시 높이 200px까지 펼치기
  =================================== */

  $("#slideDownBtn").click(function () {

    $(".yellow-box").slideDown(1000);

  });



  /* ===================================
     6. slideToggle
     #c8ff00 박스

     첫 클릭  → 높이 0
     다음 클릭 → 높이 200px
  =================================== */

  $("#slideToggleBtn").click(function () {

    $(".lime-box").slideToggle(1000);

  });



  /* ===================================
     7. ani1
     하늘색 박스를 현재 위치에서
     오른쪽으로 500px 이동
  =================================== */

  $("#ani1Btn").click(function () {

    $(".animation-box").animate(
      {
        left: "500px"
      },
      1000
    );

  });



  /* ===================================
     8. ani2
     하늘색 박스를
     원래 위치로 이동
  =================================== */

  $("#ani2Btn").click(function () {

    $(".animation-box").animate(
      {
        left: "0px"
      },
      1000
    );

  });


});